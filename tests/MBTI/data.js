const SCALE = [
  { v: -3, label: '非常不同意' },
  { v: -2, label: '不同意' },
  { v: -1, label: '比较不同意' },
  { v:  0, label: '中立' },
  { v:  1, label: '比较同意' },
  { v:  2, label: '同意' },
  { v:  3, label: '非常同意' }
];

/* ---- 评分：返回各维度得分（-1~+1，+为前项 / -为后项）与对应代码 ---- */
function scoreTest(answers) {
  const sums = {}, counts = {};
  Object.keys(SCALES).forEach(k => { sums[k] = 0; counts[k] = 0; });
  QUESTIONS.forEach((q, i) => {
    const v = answers[i];
    if (v === undefined || v === null) return;      // 未作答跳过
    let s = v;
    if (q.rev) s = -s;                                // 反向题取负
    sums[q.dim] += s;
    counts[q.dim]++;
  });
  // 各维度 -3~+3 映射到 0~100（+为前项）
  const pct = {};
  Object.keys(SCALES).forEach(k => {
    const n = counts[k] || 1;
    pct[k] = Math.round(((sums[k] / n + 3) / 6) * 100);
  });
  // 4 字母代码：四维 >50 取前项，<50 取后项，=50 取后项
  let code = '';
  DIMENSIONS.forEach(d => code += pct[d.key] > 50 ? d.a : d.b);
  return { pct, code, sums, counts };
}

/* ---- 工具：根据得分取配对展示（前项% 与 后项%）---- */
function pairPct(pct) {
  return DIMENSIONS.map(d => {
    const a = pct[d.key], b = 100 - a;
    return { key: d.key, aPct: a, bPct: b, labelA: d.labelA, labelB: d.labelB,
             codeA: d.a, codeB: d.b, dominant: a >= b ? d.a : d.b, aWins: a >= b };
  });
}

/* 根据百分比推断倾向强度 */
function strengthLabel(pct) {
  if (pct >= 90) return '极强';
  if (pct >= 75) return '较强';
  if (pct >= 60) return '中等偏强';
  if (pct >= 50) return '中等';
  if (pct >= 40) return '中等偏弱';
  if (pct >= 25) return '较弱';
  return '极弱';
}

