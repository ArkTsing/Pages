/* 元素构成：统计三张牌的元素分布，返回 [{el, count, share}] 降序 */
function elementBalance(draw) {
  const tally = {};
  Object.keys(ELEMENTS).forEach(function (k) { tally[k] = 0; });
  draw.forEach(function (d) { tally[d.card.el]++; });
  return Object.keys(tally)
    .map(function (k) { return { el: k, count: tally[k], share: tally[k] / draw.length }; })
    .filter(function (x) { return x.count > 0; })
    .sort(function (a, b) { return b.count - a.count; });
}

/* 数字能量：合并三张牌的 num，返回 [{num, label, desc, cards}] */
function numberEnergy(draw) {
  const out = [];
  draw.forEach(function (d) {
    const c = d.card;
    // 只统计小阿卡纳数字牌（Ace + 2–10），宫廷牌由 COURT 单独解读
    if (c.type === 'minor' && c.num !== 'A' && NUMBER_ENERGY[c.num]) {
      out.push({ num: c.num, label: NUMBER_ENERGY[c.num].label, desc: NUMBER_ENERGY[c.num].desc, cardName: c.name, suit: c.suit });
    }
  });
  return out;
}

