/* 多牌模式检测：同花色 / 同数字 / 逆位占比 / 大阿卡纳占比 */
function patternDetect(draw) {
  const suits = draw.map(function (d) { return d.card.suit; });
  const nums = draw.map(function (d) { return d.card.num; });
  const majors = draw.filter(function (d) { return d.card.type === 'major'; }).length;
  const reversed = draw.filter(function (d) { return d.reversed; }).length;
  const out = [];

  // 三张同花色
  if (suits[0] && suits[0] === suits[1] && suits[1] === suits[2]) {
    const s = SUITS[suits[0]];
    out.push('三张牌同属' + s.name + '（' + s.element + '元素），' + s.domain + '是你本次占卜最集中的课题——' + s.desc);
  } else {
    // 两张同花色（跳过 null，即大阿卡纳）
    const cnt = {};
    suits.forEach(function (s) { if (s) cnt[s] = (cnt[s] || 0) + 1; });
    const duo = Object.keys(cnt).find(function (k) { return cnt[k] === 2; });
    if (duo) {
      const s = SUITS[duo];
      out.push('有两张牌同属' + s.name + '（' + s.element + '元素），' + s.domain + '在牌阵中格外突出，值得你重点留意。');
    }
  }

  // 两张以上相同数字（如 两张 七）
  const numCnt = {};
  nums.forEach(function (n) { numCnt[n] = (numCnt[n] || 0) + 1; });
  const dupNum = Object.keys(numCnt).find(function (n) { return numCnt[n] >= 2; });
  if (dupNum && NUMBER_ENERGY[dupNum]) {
    out.push('牌阵中出现了两张「' + NUMBER_ENERGY[dupNum].label + '」——数字 ' + dupNum + ' 的能量被重复强调：' + NUMBER_ENERGY[dupNum].desc);
  }

  if (majors === 3) out.push('三张大阿卡纳同时现身，这是命运级别的信号：你正处在人生重要章节的交汇点。');
  if (reversed === 3) out.push('三张均为逆位，能量整体在「收紧与沉淀」——别急着推进，先处理内在的阻碍。');
  if (reversed === 0) out.push('三张均为正位，能量整体顺畅流动，是行动力与信心都比较充足的时期。');

  return out;
}

/* 牌阵类型分布：大阿卡纳 / 数字牌 / 宫廷牌 各占几张 */
function typeEmphasis(draw) {
  const majors = draw.filter(function (d) { return d.card.type === 'major'; }).length;
  const minors = draw.filter(function (d) { return d.card.type === 'minor'; }).length;
  const court = draw.filter(function (d) { return d.card.type === 'minor' && d.card.num >= 11; }).length;
  const number = minors - court;

  const parts = [];
  if (majors > 0) parts.push('大阿卡纳 ' + majors + ' 张');
  if (number > 0) parts.push('数字牌 ' + number + ' 张');
  if (court > 0) parts.push('宫廷牌 ' + court + ' 张');

  let desc;
  if (majors === 3) desc = '三张大阿卡纳，占卜指向人生层面的重大主题，而非日常琐事。';
  else if (majors === 2) desc = '大阿卡纳主导，重大课题正与日常生活交织，需要你认真对待。';
  else if (court >= 2) desc = '宫廷牌居多，牌阵指向「人」——你或身边的关键人物，关系与角色是关键。';
  else if (number >= 2) desc = '数字牌居多，课题落在具体的日常进程上，关乎时间、节奏与一步步的推进。';
  else if (majors === 0 && court === 0) desc = '没有大阿卡纳，也没有宫廷牌——这是一个关于当下日常功课的牌阵，答案藏在具体的行动里。';
  else desc = '大阿卡纳与生活之牌交织，宏观的指引与日常的课题并存。';

  return { text: parts.join(' · '), desc: desc };
}

