/* ---------------- 洗牌与抽牌（密码学随机） ---------------- */
function cryptoRandom() {
  const g = (typeof globalThis !== 'undefined' && globalThis.crypto) ||
            (typeof window !== 'undefined' && window.crypto) || null;
  if (g && g.getRandomValues) {
    const buf = new Uint32Array(1);
    g.getRandomValues(buf);
    return buf[0] / 4294967296;
  }
  return Math.random();
}

/* Fisher–Yates 洗牌 */
function shuffleArray(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(cryptoRandom() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

/* 按用户给出的 1–78 三个数字抽牌：
 * 先洗乱整副牌库，再取用户数字对应位置的牌（数字由用户凭直觉给出） */
function drawByNumbers(numbers) {
  const deck = shuffleArray(CARDS.map(function (c) { return c.id; }));
  return numbers.map(function (n, idx) {
    const id = deck[n - 1];
    return {
      card: CARDS.find(function (c) { return c.id === id; }),
      reversed: cryptoRandom() < 0.5,
      pos: POSITIONS[idx]
    };
  });
}

/* 校验用户输入：返回错误信息，合法则返回 null */
function validateNumbers(numbers) {
  if (!Array.isArray(numbers) || numbers.length !== 3) return '请给出三个数字。';
  for (var i = 0; i < numbers.length; i++) {
    var n = numbers[i];
    if (typeof n !== 'number' || !isFinite(n) || Math.floor(n) !== n || n < 1 || n > 78) {
      return '每个数字都必须在 1–78 之间。';
    }
  }
  if (new Set(numbers).size !== 3) return '三个数字不能重复——每张牌只能被翻开一次。';
  return null;
}

